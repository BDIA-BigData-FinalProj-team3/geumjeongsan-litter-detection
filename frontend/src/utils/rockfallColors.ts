/**
 * style_c 값에 따른 색상 반환
 * @param styleC 0-100 범위의 위험도 값
 * @returns RGB 색상 문자열
 */
export const getRockfallRiskColor = (styleC: number): string => {
  const index = Math.floor(styleC);
  if (index < 0) return ROCKFALL_RISK_COLORS[0];
  if (index >= ROCKFALL_RISK_COLORS.length) return ROCKFALL_RISK_COLORS[ROCKFALL_RISK_COLORS.length - 1];
  return ROCKFALL_RISK_COLORS[index];
};

/**
 * style_c 값에 따른 투명도가 적용된 색상 반환
 * @param styleC 0-100 범위의 위험도 값
 * @param opacity 투명도 (0-1)
 * @returns RGBA 색상 문자열
 */
export const getRockfallRiskColorWithOpacity = (styleC: number, opacity: number = 0.6): string => {
  const color = getRockfallRiskColor(styleC);
  return color.replace('rgb', 'rgba').replace(')', `,${opacity})`);
};

/**
 * 위험도 레벨 텍스트 반환
 * @param styleC 0-100 범위의 위험도 값
 * @returns 위험도 레벨 문자열
 */
export const getRockfallRiskLevel = (styleC: number): string => {
  if (styleC >= 80) return '매우 높음';
  if (styleC >= 60) return '높음';
  if (styleC >= 40) return '보통';
  if (styleC >= 20) return '낮음';
  return '매우 낮음';
};

